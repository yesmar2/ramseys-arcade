import { readFileSync, writeFileSync } from 'node:fs'
import opentype from '@shuding/opentype.js'

/**
 * The wordmark, "blıpka": Outfit Bold's letters as one outline, the i left
 * without its dot so a glowing blip can sit where the dot was. Written as data
 * for the header and footer (src/lib/wordmark.ts) and for the pictures drawn in
 * api/ (api/_og/wordmark.js), which scripts/gen-og-images.mjs reads too.
 *
 * The letters are outlines rather than text so the mark is the same wherever
 * it is drawn, whichever weights a page has loaded. The font parser is the one
 * Satori brings with @vercel/og; it reads WOFF. Run `npm run brand:wordmark`
 * after changing the letters, their spacing or the blip, then `npm run
 * icons:og` for the share images.
 */

const LETTERS = 'blıpka'
/** Font units between letters: -0.03em, set tight like the header's name always was. */
const TRACKING = -30
/** The blip's radius: a little larger than the dot it replaces, so it reads as a light. */
const BLIP_R = 95
/**
 * How the blip shines on each ground: its colour, and a glow `reach` times its
 * radius across, fading through `stops` of [offset, opacity]. On dark it
 * spreads; on light it stays close, or it reads as a smudge.
 */
const SHINE = {
  dark: {
    core: '#9dfce4',
    glow: '#3ee0b0',
    reach: 4.7,
    stops: [[0, 0.9], [0.21, 0.75], [0.33, 0.45], [0.5, 0.2], [0.75, 0.07], [1, 0]],
  },
  light: {
    core: '#13b388',
    glow: '#13b388',
    reach: 2.2,
    stops: [[0, 0.5], [0.45, 0.42], [0.7, 0.14], [1, 0]],
  },
}

const bytes = readFileSync('node_modules/@fontsource/outfit/files/outfit-latin-700-normal.woff')
const font = opentype.parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength))
if (font.unitsPerEm !== 1000) throw new Error(`expected 1000 units to the em, got ${font.unitsPerEm}`)

// Lay the letters out with the font's own kerning, then the tracking.
const outline = new opentype.Path()
let x = 0
let prev = null
let dotlessAt = null
for (const char of LETTERS) {
  const glyph = font.charToGlyph(char)
  if (!glyph.index) throw new Error(`Outfit has no glyph for ${char}`)
  if (prev) x += font.getKerningValue(prev, glyph) + TRACKING
  if (char === 'ı') dotlessAt = x
  outline.extend(glyph.getPath(x, 0, 1000))
  x += glyph.advanceWidth
  prev = glyph
}

// The blip goes where the i's own dot would be: the highest contour of a dotted i set in the same place.
const contours = []
for (const cmd of font.charToGlyph('i').getPath(dotlessAt, 0, 1000).commands) {
  if (cmd.type === 'M') contours.push(new opentype.Path())
  contours.at(-1).commands.push(cmd)
}
const dot = contours.map((c) => bounds(c.commands)).sort((a, b) => a.y1 - b.y1)[0]
const blip = { cx: round((dot.x1 + dot.x2) / 2), cy: round((dot.y1 + dot.y2) / 2), r: BLIP_R }

const ink = bounds(outline.commands)
const top = Math.min(ink.y1, blip.cy - blip.r)
const box = {
  x: round(ink.x1),
  y: round(top),
  width: round(ink.x2 - ink.x1),
  height: round(ink.y2 - top),
}
// The parser draws a line to where each curve already is; drop those so the outline stays small.
let pen = null
outline.commands = outline.commands.filter((c) => {
  const still = c.type === 'L' && pen && round(c.x) === round(pen.x) && round(c.y) === round(pen.y)
  if (c.type !== 'Z') pen = c
  return !still
})
const letters = outline.toPathData(1)

function round(n) {
  return Math.round(n * 10) / 10
}

/** The box around a run of path commands, its curves sampled finely enough for a tenth of a unit. */
function bounds(commands) {
  const box = { x1: Infinity, y1: Infinity, x2: -Infinity, y2: -Infinity }
  const add = (px, py) => {
    box.x1 = Math.min(box.x1, px)
    box.y1 = Math.min(box.y1, py)
    box.x2 = Math.max(box.x2, px)
    box.y2 = Math.max(box.y2, py)
  }
  let px = 0
  let py = 0
  for (const c of commands) {
    if (c.type === 'Q' || c.type === 'C') {
      for (let i = 1; i <= 64; i++) {
        const t = i / 64
        const u = 1 - t
        if (c.type === 'Q') {
          add(u * u * px + 2 * u * t * c.x1 + t * t * c.x, u * u * py + 2 * u * t * c.y1 + t * t * c.y)
        } else {
          add(
            u * u * u * px + 3 * u * u * t * c.x1 + 3 * u * t * t * c.x2 + t * t * t * c.x,
            u * u * u * py + 3 * u * u * t * c.y1 + 3 * u * t * t * c.y2 + t * t * t * c.y,
          )
        }
      }
    }
    if (c.type !== 'Z') {
      add(c.x, c.y)
      px = c.x
      py = c.y
    }
  }
  return box
}

const about = [
  '// Generated by scripts/gen-wordmark.mjs from Outfit Bold (@fontsource/outfit, latin).',
  '// Outfit: Copyright 2021 The Outfit Project Authors, SIL Open Font License 1.1.',
  '',
  '/**',
  ' * The wordmark in font units, 1000 to the em, on a baseline at y 0 (up is',
  ' * negative): the letters of "blıpka" as one outline, the blip that dots its',
  ' * i, and the box around both. `shine` is how the blip looks on a dark ground',
  ' * and on a light one; its glow spills out of the box.',
  ' */',
]
const shine = (s) =>
  `{ core: '${s.core}', glow: '${s.glow}', reach: ${s.reach}, stops: [${s.stops.map(([o, a]) => `[${o}, ${a}]`).join(', ')}] }`
const data = `{
  letters: '${letters}',
  blip: { cx: ${blip.cx}, cy: ${blip.cy}, r: ${blip.r} },
  box: { x: ${box.x}, y: ${box.y}, width: ${box.width}, height: ${box.height} },
  shine: {
    dark: ${shine(SHINE.dark)},
    light: ${shine(SHINE.light)},
  },
}`

writeFileSync('src/lib/wordmark.ts', [...about, `export const WORDMARK = ${data}`, ''].join('\n'))
writeFileSync(
  'api/_og/wordmark.js',
  [
    ...about.slice(0, 3),
    '/** @typedef {{ core: string, glow: string, reach: number, stops: number[][] }} Shine */',
    '',
    ...about.slice(3, -1),
    ' * @type {{ letters: string, blip: { cx: number, cy: number, r: number }, box: { x: number, y: number, width: number, height: number }, shine: { dark: Shine, light: Shine } }}',
    ' */',
    `export const WORDMARK = ${data}`,
    '',
  ].join('\n'),
)
console.log('wrote src/lib/wordmark.ts and api/_og/wordmark.js', { blip, box, dot: { x1: round(dot.x1), x2: round(dot.x2), y1: round(dot.y1), y2: round(dot.y2) } })
