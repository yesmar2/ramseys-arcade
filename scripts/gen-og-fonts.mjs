import { readFileSync, writeFileSync } from 'node:fs'

/**
 * The site's font, Outfit, for the challenge cards drawn in api/.
 *
 * The functions draw text with Satori, which needs the font's bytes. They are
 * written into a module as base64, so they travel inside the function's code
 * and nothing depends on how the host bundles loose files. Outfit is under
 * the SIL Open Font License 1.1, which allows embedding it. Run
 * `node scripts/gen-og-fonts.mjs` after changing the weights.
 */

const WEIGHTS = [400, 600, 700]

const fonts = WEIGHTS.map((weight) => {
  const bytes = readFileSync(`node_modules/@fontsource/outfit/files/outfit-latin-${weight}-normal.woff`)
  return `  { weight: ${weight}, base64: '${bytes.toString('base64')}' },`
})

writeFileSync(
  'api/_og/fonts.js',
  [
    '// Generated by scripts/gen-og-fonts.mjs from @fontsource/outfit (latin).',
    '// Outfit: Copyright 2021 The Outfit Project Authors, SIL Open Font License 1.1.',
    '',
    '/** @type {{ weight: 400 | 600 | 700, base64: string }[]} */',
    'export const OUTFIT = [',
    ...fonts,
    ']',
    '',
  ].join('\n'),
)
console.log(`wrote api/_og/fonts.js (${WEIGHTS.join(', ')})`)
